// Types
export type TierLevel = 'Patron' | 'Apprentice' | 'Maker' | 'Artisan' | 'Elder'
export type QualityRating = 'Standard' | 'Excellent' | 'Exceptional' | 'Innovation'
export type ProposalStatus = 'voting' | 'passed' | 'rejected' | 'upcoming'
export type ProposalCategory = 'Governance' | 'Treasury' | 'Exhibition' | 'Membership' | 'Standards' | 'Community'

export interface ReputationDimensions {
  artworkQuality: number
  communityEngagement: number
  peerReview: number
  exhibition: number
  mentorship: number
  platformDev: number
}

export interface User {
  id: string
  name: string
  tier: TierLevel
  reputation: number
  reputationDimensions: ReputationDimensions
  avatar: string
  joinDate: string
  badges: string[] // badge IDs
}

export interface Artwork {
  id: string
  title: string
  artistId: string
  artistName: string
  quality: QualityRating
  status: 'review' | 'approved' | 'gallery'
  uploadDate: string
  reviewCount: number
  feedbackNotes: FeedbackNote[]
  category: string
  description: string
  imageUrl: string
  views: number
  favorites: number
  sales: number
  conversionRate: number
}

export interface FeedbackNote {
  id: string
  reviewerId: string
  reviewerName: string
  content: string
  date: string
}

export interface Proposal {
  id: string
  title: string
  category: ProposalCategory
  description: string
  status: ProposalStatus
  votePercentage: number
  totalVotes: number
  votingEnds: string
  proposedBy: string
  proposedDate: string
}

export interface Badge {
  id: string
  name: string
  description: string
  category: string
  rarity: 'Common' | 'Uncommon' | 'Rare' | 'Epic' | 'Legendary'
  earnedDate?: string
  progress?: number
  requirements: string
  heldByPercentage: number
  icon: string
}

export interface ForumThread {
  id: string
  title: string
  authorId: string
  authorName: string
  category: string
  createdDate: string
  lastActivity: string
  replyCount: number
  views: number
  isPinned: boolean
  posts: ForumPost[]
}

export interface ForumPost {
  id: string
  threadId: string
  authorId: string
  authorName: string
  content: string
  createdDate: string
  upvotes: number
  replies?: ForumPost[]
}

